-- workspace scroll (clamped to 1..5)
local function scroll_workspace(delta)
    local ws = hl.get_active_workspace()
    if not ws then return end
    local target = ws.id + delta
    if target < 1 then target = 1 end
    if target > 5 then target = 5 end
    if target ~= ws.id then
        hl.dispatch(hl.dsp.focus({ workspace = target }))
    end
end
hl.bind(mainMod .. " + mouse_down", function() scroll_workspace(1) end)
hl.bind(mainMod .. " + mouse_up",   function() scroll_workspace(-1) end)

